#!/usr/bin/env python3
"""Project skills for Claude Code and Codex from one pinned source (docs/GROUND_UP_WORKFLOW_DESIGN.md
"One skill source for Claude Code and Codex").

  python -I tools/skills.py vendor [--revision SHA]   copy the manifest's skills from upstream into
                                                     workflow/skills/upstream/ (network; for updates)
  python -I tools/skills.py generate                 write .claude/skills/eaw-*/ and .agents/skills/eaw-*/
  python -I tools/skills.py check                    fail unless both generated trees match the source, every
                                                     skill's metadata parses, every skill reference resolves and
                                                     no two project skills share a name
  python -I tools/skills.py selftest

workflow/skills/manifest.json lists each skill: its upstream path, its invocation policy ("user": only the user starts
it; "model": the agent may also start it when the task calls for it) and its local adaptations. An adaptation is an
exact find / replace on one file of the upstream copy, or text appended to it; a find that no longer matches fails
generate and check, so an upstream update cannot silently drop a project change. The generated folders are ordinary
checked-in files (no symlinks). Standard library only.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import sys
import tempfile
import unittest
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "workflow", "skills")
MANIFEST = os.path.join(SOURCE, "manifest.json")
UPSTREAM = os.path.join(SOURCE, "upstream")
OUTPUTS = {"claude": os.path.join(ROOT, ".claude", "skills"), "codex": os.path.join(ROOT, ".agents", "skills")}
GENERATED_NOTE = ("generated by tools/skills.py from workflow/skills (adapted from mattpocock/skills, MIT: "
                  "workflow/skills/upstream/LICENSE); edit the source, then run tools/skills.py generate")


def load_manifest(path: str = MANIFEST) -> dict:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


# ------------------------------------------------------------------------------------------------- vendor

def _get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "eaw-skills-vendor"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def vendor(revision: str | None) -> int:
    m = load_manifest()
    repo, rev = m["upstream"]["repo"], revision or m["upstream"]["revision"]
    tree = json.loads(_get(f"https://api.github.com/repos/{repo}/git/trees/{rev}?recursive=1"))
    blobs = [t["path"] for t in tree["tree"] if t["type"] == "blob"]
    if os.path.isdir(UPSTREAM):
        shutil.rmtree(UPSTREAM)
    count = 0
    for name, s in sorted(m["skills"].items()):
        prefix = s["path"].rstrip("/") + "/"
        files = [p for p in blobs if p.startswith(prefix)]
        if not any(p == prefix + "SKILL.md" for p in files):
            print(f"skills.py: {s['path']} has no SKILL.md at {rev}")
            return 1
        for p in files:
            dst = os.path.join(UPSTREAM, name, *p[len(prefix):].split("/"))
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            with open(dst, "wb") as f:
                f.write(_get(f"https://raw.githubusercontent.com/{repo}/{rev}/{p}"))
            count += 1
    with open(os.path.join(UPSTREAM, "LICENSE"), "wb") as f:
        f.write(_get(f"https://raw.githubusercontent.com/{repo}/{rev}/LICENSE"))
    if rev != m["upstream"]["revision"]:
        m["upstream"]["revision"] = rev
        with open(MANIFEST, "w", encoding="utf-8", newline="\n") as f:
            json.dump(m, f, indent=2)
            f.write("\n")
    print(f"skills.py: vendored {len(m['skills'])} skills ({count} files) from {repo}@{rev}")
    return 0


# ------------------------------------------------------------------------------------------------- generate

class SkillError(Exception):
    pass


def _ref_patterns(names: list[str], prefix: str) -> list[tuple[re.Pattern, str]]:
    alt = "|".join(re.escape(n) for n in sorted(names, key=len, reverse=True))
    return [
        # "Call the Skill tool with "tdd"", "for "grilling" and "domain-modeling"": quoted names on a Skill-tool line
        (re.compile(rf'(?im)^(?=.*skill tool).*$'), "line"),
        # "the `code-review` skill", "Call the Skill tool with `writing-for-agents`"
        (re.compile(rf'`({alt})`(?= skill\b)'), f"`{prefix}\\1`"),
        # slash commands: `/setup-matt-pocock-skills`, /triage
        (re.compile(rf'(?<=[\s`(])/({alt})(?![\w-])'), f"/{prefix}\\1"),
    ]


def rename_refs(text: str, names: list[str], prefix: str) -> str:
    """Points references to the manifest's skills at their prefixed names; other mentions are left alone."""
    alt = "|".join(re.escape(n) for n in sorted(names, key=len, reverse=True))
    # On a Skill-tool line: "name" anywhere, `name` only right after "Skill tool with" (a backticked word elsewhere on
    # the line can be something else, e.g. wayfinder's `research` ticket type).
    quoted = re.compile(rf'"({alt})"|(?<=skill tool with )`({alt})`', re.I)

    def fix_line(m: re.Match) -> str:
        return quoted.sub(lambda q: f'"{prefix}{q.group(1)}"' if q.group(1) else f"`{prefix}{q.group(2)}`", m.group(0))

    line_pat, _ = _ref_patterns(names, prefix)[0]
    text = line_pat.sub(fix_line, text)
    for pat, repl in _ref_patterns(names, prefix)[1:]:
        text = pat.sub(repl, text)
    return text


def unresolved_refs(text: str, names: list[str], prefix: str, known: set[str]) -> list[str]:
    """References in generated text that still name an unprefixed manifest skill, or a prefixed one that does not exist."""
    bad = []
    alt = "|".join(re.escape(n) for n in sorted(names, key=len, reverse=True))
    for line in text.splitlines():
        if re.search(r"(?i)skill tool", line):
            for m in re.finditer(rf'"({alt})"|(?<=skill tool with )`({alt})`', line, re.I):
                bad.append(f"unprefixed skill reference {m.group(0)}")
        for m in re.finditer(rf'`({alt})` skill\b', line):
            bad.append(f"unprefixed skill reference {m.group(0)}")
        for m in re.finditer(rf'(?<=[\s`(])/({alt})(?![\w-])', line):
            bad.append(f"unprefixed slash command {m.group(0)}")
        for m in re.finditer(rf'(?<![\w-]){re.escape(prefix)}([a-z][\w-]*)', line):
            if prefix + m.group(1) not in known:
                bad.append(f"unknown project skill {prefix}{m.group(1)}")
    return bad


def split_frontmatter(text: str) -> tuple[list[str], str]:
    if not text.startswith("---\n"):
        raise SkillError("SKILL.md does not start with a --- frontmatter block")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise SkillError("SKILL.md frontmatter is not closed")
    return text[4:end].split("\n"), text[end + 5:]


def frontmatter_value(lines: list[str], key: str) -> str | None:
    for line in lines:
        if line.startswith(key + ":"):
            return line.split(":", 1)[1].strip().strip('"')
    return None


def rewrite_skill_md(text: str, new_name: str, client: str, invocation: str) -> str:
    fm, body = split_frontmatter(text)
    out = []
    for line in fm:
        if line.startswith("disable-model-invocation:"):
            continue
        if line.startswith("name:"):
            out.append(f"name: {new_name}")
            if client == "claude" and invocation == "user":
                out.append("disable-model-invocation: true")
            continue
        out.append(line)
    if not any(line.startswith("name:") for line in fm):
        raise SkillError("SKILL.md frontmatter has no name")
    return "---\n" + "\n".join(out) + "\n---\n\n<!-- " + GENERATED_NOTE + " -->\n" + body


def rewrite_openai_yaml(text: str, invocation: str) -> str:
    out, skipping = [], False
    for line in text.replace("\r\n", "\n").split("\n"):
        if line.startswith("policy:"):
            skipping = True
            continue
        if skipping and (line.startswith(" ") or not line.strip()):
            continue
        skipping = False
        out.append(line)
    body = "\n".join(out).rstrip("\n") + "\n"
    if invocation == "user":
        body += "policy:\n  allow_implicit_invocation: false\n"
    return f"# {GENERATED_NOTE}\n" + body


def apply_adaptations(files: dict[str, str], adaptations: list[dict], skill: str) -> None:
    for a in adaptations:
        f = a["file"]
        if f not in files:
            raise SkillError(f"{skill}: adaptation names {f}, which upstream does not have")
        if "append" in a:
            files[f] = files[f].rstrip("\n") + "\n\n" + a["append"].rstrip("\n") + "\n"
        else:
            n = files[f].count(a["find"])
            if n != 1:
                raise SkillError(f"{skill}/{f}: adaptation text found {n} times (upstream changed?): {a['find'][:70]!r}")
            files[f] = files[f].replace(a["find"], a["replace"])


def build(manifest: dict, upstream: str = UPSTREAM) -> dict[str, dict[str, bytes]]:
    """client -> {relative path: bytes} for both generated trees."""
    prefix, skills = manifest["prefix"], manifest["skills"]
    names = list(skills)
    known = {prefix + n for n in names}
    if len(known) != len(names):
        raise SkillError("duplicate skill names in the manifest")
    out: dict[str, dict[str, bytes]] = {"claude": {}, "codex": {}}
    for name, s in sorted(skills.items()):
        if s.get("invocation") not in ("user", "model"):
            raise SkillError(f"{name}: invocation must be 'user' or 'model'")
        src = os.path.join(upstream, name)
        if not os.path.isfile(os.path.join(src, "SKILL.md")):
            raise SkillError(f"{name}: workflow/skills/upstream/{name}/SKILL.md missing (run tools/skills.py vendor)")
        files: dict[str, str] = {}
        for dirpath, _, filenames in os.walk(src):
            for fn in filenames:
                rel = os.path.relpath(os.path.join(dirpath, fn), src).replace(os.sep, "/")
                with open(os.path.join(dirpath, fn), encoding="utf-8", newline="") as f:
                    files[rel] = f.read().replace("\r\n", "\n")
        apply_adaptations(files, s.get("adaptations", []), name)
        new = prefix + name
        for rel, text in files.items():
            if rel.endswith(".md"):
                files[rel] = rename_refs(text, names, prefix)
        for client in ("claude", "codex"):
            for rel, text in sorted(files.items()):
                if rel.startswith("agents/") and client == "claude":
                    continue
                if rel == "SKILL.md":
                    text = rewrite_skill_md(text, new, client, s["invocation"])
                elif rel == "agents/openai.yaml":
                    text = rewrite_openai_yaml(text, s["invocation"])
                out[client][f"{new}/{rel}"] = text.encode("utf-8")
            if client == "codex" and "agents/openai.yaml" not in files:
                raise SkillError(f"{name}: upstream has no agents/openai.yaml for Codex")
        for rel, text in files.items():
            if rel.endswith(".md"):
                bad = unresolved_refs(text if rel != "SKILL.md" else rewrite_skill_md(text, new, "claude", "model"),
                                      names, prefix, known)
                if bad:
                    raise SkillError(f"{new}/{rel}: " + "; ".join(sorted(set(bad))))
    return out


def write_tree(files: dict[str, bytes], dest: str, prefix: str) -> None:
    os.makedirs(dest, exist_ok=True)
    for entry in os.listdir(dest):  # remove only generated skills; other project skills are left alone
        if entry.startswith(prefix):
            shutil.rmtree(os.path.join(dest, entry))
    for rel, data in files.items():
        p = os.path.join(dest, *rel.split("/"))
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "wb") as f:
            f.write(data)


def read_tree(dest: str, prefix: str) -> dict[str, bytes]:
    out = {}
    if not os.path.isdir(dest):
        return out
    for entry in os.listdir(dest):
        if not entry.startswith(prefix):
            continue
        for dirpath, _, filenames in os.walk(os.path.join(dest, entry)):
            for fn in filenames:
                p = os.path.join(dirpath, fn)
                with open(p, "rb") as f:
                    out[os.path.relpath(p, dest).replace(os.sep, "/")] = f.read().replace(b"\r\n", b"\n")
    return out


def generate() -> int:
    m = load_manifest()
    try:
        trees = build(m)
    except SkillError as e:
        print(f"skills.py: {e}")
        return 1
    for client, files in trees.items():
        write_tree(files, OUTPUTS[client], m["prefix"])
    print(f"skills.py: generated {len(m['skills'])} skills into .claude/skills and .agents/skills")
    return 0


def validate_tree(files: dict[str, bytes], client: str, manifest: dict) -> list[str]:
    errs = []
    prefix = manifest["prefix"]
    for name, s in manifest["skills"].items():
        new = prefix + name
        raw = files.get(f"{new}/SKILL.md")
        if raw is None:
            errs.append(f"{client}: {new}/SKILL.md missing")
            continue
        try:
            fm, _ = split_frontmatter(raw.decode("utf-8"))
        except SkillError as e:
            errs.append(f"{client}: {new}/SKILL.md: {e}")
            continue
        if frontmatter_value(fm, "name") != new:
            errs.append(f"{client}: {new}/SKILL.md name is {frontmatter_value(fm, 'name')!r}")
        if not frontmatter_value(fm, "description"):
            errs.append(f"{client}: {new}/SKILL.md has no description")
        disabled = frontmatter_value(fm, "disable-model-invocation") == "true"
        if client == "claude" and disabled != (s["invocation"] == "user"):
            errs.append(f"claude: {new} disable-model-invocation does not match invocation {s['invocation']}")
        if client == "codex":
            y = files.get(f"{new}/agents/openai.yaml", b"").decode("utf-8")
            if "display_name:" not in y or "short_description:" not in y:
                errs.append(f"codex: {new}/agents/openai.yaml lacks interface.display_name / short_description")
            if ("allow_implicit_invocation: false" in y) != (s["invocation"] == "user"):
                errs.append(f"codex: {new} allow_implicit_invocation does not match invocation {s['invocation']}")
    return errs


def check() -> int:
    m = load_manifest()
    try:
        trees = build(m)
    except SkillError as e:
        print(f"skills.py check: {e}")
        return 1
    errs = []
    for client, want in trees.items():
        have = read_tree(OUTPUTS[client], m["prefix"])
        rel_out = os.path.relpath(OUTPUTS[client], ROOT)
        for p in sorted(set(want) - set(have)):
            errs.append(f"{rel_out}/{p}: missing")
        for p in sorted(set(have) - set(want)):
            errs.append(f"{rel_out}/{p}: not generated from workflow/skills (stale or hand-made)")
        for p in sorted(set(want) & set(have)):
            if want[p] != have[p]:
                errs.append(f"{rel_out}/{p}: differs from the generated file")
        errs += validate_tree(want, client, m)
        # A hand-made project skill must not take a generated skill's name.
        if os.path.isdir(OUTPUTS[client]):
            for entry in os.listdir(OUTPUTS[client]):
                fm_path = os.path.join(OUTPUTS[client], entry, "SKILL.md")
                if entry.startswith(m["prefix"]) or not os.path.isfile(fm_path):
                    continue
                with open(fm_path, encoding="utf-8") as f:
                    try:
                        nm = frontmatter_value(split_frontmatter(f.read().replace("\r\n", "\n"))[0], "name")
                    except SkillError:
                        continue
                if nm and nm.startswith(m["prefix"]):
                    errs.append(f"{rel_out}/{entry}: a hand-made skill uses the project prefix ({nm})")
    if errs:
        print("skills.py check: FAILED (fix workflow/skills, then run: python -I tools/skills.py generate)")
        for e in errs:
            print("  " + e)
        return 1
    print(f"skills.py check: {len(m['skills'])} skills, both trees match the source, metadata and references valid")
    return 0


# ------------------------------------------------------------------------------------------------- self-test

class _Tests(unittest.TestCase):
    NAMES = ["tdd", "code-review", "grilling", "domain-modeling", "research", "setup-matt-pocock-skills"]

    def test_rename_skill_tool_and_slash(self):
        t = rename_refs('Call the Skill tool twice, for "grilling" and "domain-modeling".\nRun `/setup-matt-pocock-skills`.',
                        self.NAMES, "eaw-")
        self.assertIn('"eaw-grilling" and "eaw-domain-modeling"', t)
        self.assertIn("`/eaw-setup-matt-pocock-skills`", t)

    def test_rename_leaves_other_mentions(self):
        t = rename_refs('For each `research` ticket, a subagent calls the Skill tool with "research".\nsee the `tdd` skill',
                        self.NAMES, "eaw-")
        self.assertIn("each `research` ticket", t)
        self.assertIn('Skill tool with "eaw-research"', t)
        self.assertIn("the `eaw-tdd` skill", t)
        self.assertEqual(rename_refs("docs/adr/ and skills/engineering/tdd/", self.NAMES, "eaw-"),
                         "docs/adr/ and skills/engineering/tdd/")

    def test_unresolved_refs(self):
        known = {"eaw-tdd"}
        self.assertEqual(unresolved_refs('Call the Skill tool with "eaw-tdd".', self.NAMES, "eaw-", known), [])
        self.assertTrue(unresolved_refs('Call the Skill tool with "tdd".', self.NAMES, "eaw-", known))
        self.assertTrue(unresolved_refs("run /eaw-nothing", self.NAMES, "eaw-", known))

    def test_frontmatter_and_policy(self):
        md = "---\nname: tdd\ndescription: x\ndisable-model-invocation: true\n---\nbody\n"
        c = rewrite_skill_md(md, "eaw-tdd", "claude", "user")
        self.assertIn("name: eaw-tdd\ndisable-model-invocation: true", c)
        x = rewrite_skill_md(md, "eaw-tdd", "codex", "user")
        self.assertNotIn("disable-model-invocation", x)
        self.assertNotIn("disable-model-invocation", rewrite_skill_md(md, "eaw-tdd", "claude", "model"))
        y = 'interface:\n  display_name: "T"\npolicy:\n  allow_implicit_invocation: false\n'
        self.assertNotIn("policy", rewrite_openai_yaml(y, "model"))
        self.assertIn("allow_implicit_invocation: false", rewrite_openai_yaml(y, "user"))

    def test_adaptation_must_match_once(self):
        files = {"SKILL.md": "a b a"}
        with self.assertRaises(SkillError):
            apply_adaptations(files, [{"file": "SKILL.md", "find": "a", "replace": "c"}], "s")
        with self.assertRaises(SkillError):
            apply_adaptations(files, [{"file": "SKILL.md", "find": "zzz", "replace": "c"}], "s")
        apply_adaptations(files, [{"file": "SKILL.md", "find": "b", "replace": "c"}, {"file": "SKILL.md", "append": "end"}], "s")
        self.assertEqual(files["SKILL.md"], "a c a\n\nend\n")


def selftest() -> int:
    suite = unittest.defaultTestLoader.loadTestsFromTestCase(_Tests)
    return 0 if unittest.TextTestRunner(verbosity=1).run(suite).wasSuccessful() else 1


def main(argv: list[str]) -> int:
    if argv[:1] == ["vendor"]:
        rev = argv[argv.index("--revision") + 1] if "--revision" in argv else None
        return vendor(rev)
    if argv[:1] == ["generate"]:
        return generate()
    if argv[:1] == ["check"]:
        return check()
    if argv[:1] == ["selftest"]:
        return selftest()
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
